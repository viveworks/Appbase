package com.viveworks.appbase.stacktest.test;

import com.viveworks.appbase.bootstrap.service.AppbaseServices;
import org.apache.http.client.CookieStore;
import org.apache.http.client.HttpClient;

/**
 * @author Navaneeth Mysore G
 * @since 1.0.0
 */
public abstract class AbstractResourceTest extends AbstractTest implements ResourceTest {
    public AbstractResourceTest(
            final AppbaseServices appbaseServices,
            final HttpClient httpClient,
            final CookieStore cookieStore,
            final String baseUrl)
    {
        super(appbaseServices, httpClient, cookieStore, baseUrl);
    }

    protected void beforeAllTests() {
        // no-op, override in sub-classes as needed
    }

    protected abstract void runResourceTestsImpl() throws Exception;

    @Override
    public void cleanupResourceTests() {
        // no-op, override in sub-classes as needed
    }

    @Override
    public void runResourceTests() throws Exception {
        beforeAllTests();
        runResourceTestsImpl();
    }
}
